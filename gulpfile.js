const { src, dest, parallel } = require('gulp');
const fs = require('fs');

function buildIcons() {
    return src(['nodes/**/*.{png,svg}', 'credentials/**/*.{png,svg}'], { base: '.' })
        .pipe(dest('dist'));
}

function createIndex(cb) {
    if (!fs.existsSync('dist')) {
        fs.mkdirSync('dist', { recursive: true });
    }
    fs.writeFileSync('dist/index.js', '// Generated by build\nmodule.exports = {};\n');
    cb();
}

exports['build:icons'] = parallel(buildIcons, createIndex);